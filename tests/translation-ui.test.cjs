const { test } = require('node:test');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const { syncTranslationToggles } = require('../app/code/renderer/modules/translation-ui.js');
const { defaultTranslationSettings } = require('../app/code/common/translation.js');
void test('switches align with names, include disabled channels, and exclude message links', () => {
  const { document } = new JSDOM('<aside><a href="/channels/9/123"><div class="linkTop"><div class="name_example">autotrans</div><button>Settings</button></div></a><a href="/channels/9/456"><span class="name_example">general</span></a></aside><main><a href="/channels/9/123">message link</a><form><div contenteditable="true"></div></form></main>', { url: 'https://discord.com' }).window;
  const settings = { ...defaultTranslationSettings, consent: true, channels: { '123': { enabled: true, target: 'en' } } };
  let calls = 0;
  const toggle = async () => { calls++; };
  syncTranslationToggles(document, settings, toggle);
  const controls = document.querySelectorAll('[data-xikii-translation-toggle]');
  assert.equal(controls.length, 2);
  const control = controls[0];
  assert.equal(control.parentElement.className, 'linkTop');
  assert.equal(control.previousElementSibling.textContent, 'autotrans');
  assert.equal(control.textContent, ''); assert.equal(control.style.width, '24px');
  assert.equal(control.getAttribute('aria-checked'), 'true');
  assert.equal(controls[1].getAttribute('aria-checked'), 'false');
  syncTranslationToggles(document, settings, toggle, '123');
  assert.equal(control.getAttribute('aria-busy'), 'true');
  assert.equal(document.querySelectorAll('[data-xikii-translation-toggle]').length, 2);
  control.click(); assert.equal(calls, 0, 'page-generated clicks cannot change preferences');
  syncTranslationToggles(document, { ...settings, consent: false }, toggle);
  assert.equal(control.getAttribute('aria-checked'), 'false');
  assert.equal(document.querySelector('form').children.length, 1, 'no translation UI is inserted in the composer');
});
